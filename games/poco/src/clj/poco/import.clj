(ns poco.import
  "Turns the pictures in resources/assets/sprites/player (drawn in Aseprite, one
  PNG per frame, 16x32) into the data poco.core builds from:
  resources/assets/sprites/player/player.edn, which says which colors are in the
  sprite palettes, what the tiles look like, and where each frame's eight
  sprites go. See cartridj.sprites for what it checks.

    clojure -T:build import                          ; every picture
    clojure -T:build import :only '[\"player-03\"]'   ; just some

  Run it again when the pictures change. The EDN it writes is kept in the
  repository, so building the game needs no PNG reader.

  The background's tiles come from sheets (see `import-tiles`):

    clojure -T:build tiles"
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [cartridj.sheets :as sheets]
            [cartridj.sprites :as sprites]))

(def pictures "resources/assets/sprites/player")
(def output "resources/assets/sprites/player/player.edn")

(defn import-sprites
  "`only` is a vector of picture names (\"player-03\"), or nil for all."
  [only]
  (let [art (sprites/import! pictures output
                             :only only
                             ;; tile 0 is the blank one (poco.core/tiles), so ours start at 1
                             :first-tile 1)]
    (println (count (:frames art)) "frames:" (mapv :name (:frames art)))
    (println (count (:tiles art)) "tiles;" (count (:palettes art)) "sprite palettes:"
             (mapv #(mapv (partial format "$%02X") %) (:palettes art)))
    (println "wrote" output)
    art))

(def assets "resources/assets")

(defn- read-edn [file] (edn/read-string (slurp (io/file assets file))))

(defn import-tiles
  "Read the cells of the tilesheets (the PNGs that tiles.edn's :sheets name)
  that its tiles come from, and write what's in them to sheets.edn. Options
  as for cartridj.sheets/import-cells: `:nearest? true` takes the closest
  of a palette's colors for pixels that aren't exactly one."
  [options]
  (let [tiles (read-edn "tiles.edn")
        cells (sheets/import-cells (merge {:dir assets
                                           :sheets (:sheets tiles)
                                           :assets (:metatiles tiles)
                                           :palettes (read-edn "palettes.edn")}
                                          options))
        out (str assets "/sheets.edn")]
    (sheets/write-cells! out cells
                         (str ";; GENERATED by `clojure -T:build tiles` (poco.import) from the tilesheets:\n"
                              ";; what's in the cells that tiles.edn uses. Change the pictures, not this.\n"))
    (println (reduce + (map count (vals cells))) "tiles from" (count cells) "sheet(s); wrote" out)
    cells))
